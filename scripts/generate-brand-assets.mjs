/**
 * Generates the static brand rasters in public/ from SVG defined here.
 *
 * Run manually (`npm run assets`) rather than as part of `astro build`: the
 * output is committed, so the deploy does not depend on the build machine
 * having sharp's system dependencies, and the hosted build stays fast.
 *
 * Produces:
 *   public/apple-touch-icon.png   180x180, for iOS home screens
 *   public/logo.png               512x512, referenced by Organization JSON-LD
 *   public/og/default.png         1200x630, the social card
 *
 * The name and domain are imported from src/lib/site.ts rather than retyped,
 * so a rename cannot leave the OG card showing the previous site's name. The
 * colours cannot be imported -- they live in CSS -- so they are duplicated
 * below and must be kept in step with global.css by hand.
 */
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { SITE } from '../src/lib/site.ts';

/** RENAME: keep in step with --color-accent-600 and friends in global.css. */
const ACCENT = '#4f46e5';
const BG = '#fbfbfa';
const INK = '#1a1a18';
const MUTED = '#57574f';
/**
 * Fonts available to librsvg inside sharp, NOT the site's webfonts. Whatever is
 * installed on this machine is what renders; the fallback chain matters more
 * than the first entry.
 */
const FONT = 'DejaVu Sans, Liberation Sans, Arial, sans-serif';

/**
 * The brand mark. Geometry is identical to public/favicon.svg and
 * src/components/Logo.astro -- change one, change all three, then re-run this.
 */
const mark = (cx, cy, s, fill) => `
  <g transform="translate(${cx} ${cy}) scale(${s}) translate(-16 -16)">
    <path d="M16 7.5A8.5 8.5 0 1 1 9.99 9.99" fill="none" stroke="${fill}" stroke-width="3" stroke-linecap="round"/>
    <circle cx="16" cy="16" r="3" fill="${fill}"/>
  </g>`;

const icon = (size, radius) => `
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  <rect width="${size}" height="${size}" rx="${radius}" fill="${ACCENT}"/>
  ${mark(size / 2, size / 2, (size / 32) * 0.78, '#fff')}
</svg>`;

/**
 * The social card.
 *
 * Deliberately typographic rather than a screenshot: a screenshot is stale the
 * week after it is taken, and this file is regenerated by a script that already
 * knows the site's name. RENAME: the two headline lines are the only copy here.
 */
const ogCard = `
<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="${BG}"/>
  <rect x="0" y="0" width="1200" height="10" fill="${ACCENT}"/>
  <rect x="72" y="72" width="64" height="64" rx="14" fill="${ACCENT}"/>
  ${mark(104, 104, 1.55, '#fff')}
  <text x="156" y="118" font-family="${FONT}" font-size="34" font-weight="700" fill="${INK}">${SITE.name}</text>

  <text x="72" y="280" font-family="${FONT}" font-size="62" font-weight="700" fill="${INK}">Headline line one,</text>
  <text x="72" y="356" font-family="${FONT}" font-size="62" font-weight="700" fill="${INK}">and <tspan fill="${ACCENT}">line two</tspan>.</text>

  <text x="72" y="440" font-family="${FONT}" font-size="28" fill="${MUTED}">${SITE.tagline}.</text>

  <rect x="72" y="510" width="360" height="54" rx="12" fill="${ACCENT}"/>
  <text x="98" y="545" font-family="${FONT}" font-size="26" font-weight="700" fill="#fff">${SITE.domain}</text>
</svg>`;

const jobs = [
  ['public/apple-touch-icon.png', icon(180, 40)],
  ['public/logo.png', icon(512, 114)],
  ['public/og/default.png', ogCard],
];

await mkdir('public/og', { recursive: true });
for (const [out, svg] of jobs) {
  const buf = await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toBuffer();
  await writeFile(out, buf);
  console.log(`${out}  ${(buf.length / 1024).toFixed(1)} KB`);
}
